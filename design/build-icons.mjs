// Regenerates the icon files from design/icons/icons.source.mjs:
//   design/icons/svg/<name>.svg   standalone SVGs (24 px, currentColor)
//   src/components/icons.tsx      React components + <Icon name="..."/>
// Usage (from the kit or repo root): node design/build-icons.mjs
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { icons } from "./icons/icons.source.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const svgDir = join(here, "icons", "svg");
mkdirSync(svgDir, { recursive: true });

const attrs =
  'viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round"';

for (const [name, inner] of Object.entries(icons)) {
  writeFileSync(
    join(svgDir, `${name}.svg`),
    `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" ${attrs}>${inner}</svg>\n`,
  );
}

const pascal = (n) => "Icon" + n.split("-").map((p) => p[0].toUpperCase() + p.slice(1)).join("");
const names = Object.keys(icons);

const tsx = `// Generated by design/build-icons.mjs from design/icons/icons.source.mjs.
// Edit the source file and regenerate; do not edit this file by hand.
import type { ReactElement, ReactNode, SVGProps } from "react";

export type IconName =
${names.map((n) => `  | "${n}"`).join("\n")};

export type IconProps = Omit<SVGProps<SVGSVGElement>, "children"> & {
  /** Accessible name. Leave it out when the icon sits next to text that says the same thing. */
  title?: string;
  /** Width and height in px. Defaults to 20. */
  size?: number;
};

function Svg({ title, size = 20, children, ...rest }: IconProps & { children: ReactNode }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      focusable="false"
      aria-hidden={title ? undefined : true}
      role={title ? "img" : undefined}
      {...rest}
    >
      {title ? <title>{title}</title> : null}
      {children}
    </svg>
  );
}

${names
  .map(
    (n) => `export function ${pascal(n)}(props: IconProps) {
  return <Svg {...props}>${icons[n]}</Svg>;
}`,
  )
  .join("\n\n")}

const registry: Record<IconName, (props: IconProps) => ReactElement> = {
${names.map((n) => `  "${n}": ${pascal(n)},`).join("\n")}
};

/** <Icon name="calendar" /> picks an icon by name, e.g. from the status map. */
export function Icon({ name, ...props }: IconProps & { name: IconName }) {
  const Component = registry[name];
  return <Component {...props} />;
}
`;
mkdirSync(join(root, "src", "components"), { recursive: true });
writeFileSync(join(root, "src", "components", "icons.tsx"), tsx);
console.log(`Wrote ${names.length} icons.`);
